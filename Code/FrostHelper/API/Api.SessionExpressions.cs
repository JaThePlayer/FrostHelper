    /// <summary>
    /// Creates a delegate which can evaluate a Session Expression efficiently.
    /// This is the recommended way to evaluate session expressions.
    /// This function should only be called once when creating an entity, the delegate should be stored for re-use.
    /// Added in Frost Helper 1.81.0
    /// </summary>
    /// <param name="str">The expression</param>
    /// <param name="context">The Session Expression Context to use, leave null to use the global context. The context object should be generated by <see cref="CreateSessionExpressionContextV2"/>.</param>
    /// <param name="returnType">The type that should be returned by the expression.</param>
    /// <returns>A delegate which evaluates the expression. Will always be of type Func{Session, object?, returnType} and can safely be cast to that type.</returns>
    public static Delegate? CreateTypedSessionExpressionOrNull(string str, object? context, Type returnType) {
        if (ConditionHelper.TryCreate(str, AssertIsOrNull<IExpressionContext>(context) ?? ExpressionContext.Default, out var expr)) {
            var compiled = CompiledCondition.GetDelegateFor(expr, returnType);
            return compiled;
        }

        return null;
    }

    /// <summary>
    /// Coerces the given value to the target type, using Session Expression rules.
    /// Added in Frost Helper 1.81.0
    /// </summary>
    public static object CoerceValueInSessionExpression(object value, Type targetType) {
        return ConditionHelper.Condition.Coerce(value, targetType);
    }
    
    /// <summary>
    /// Creates an object which can evaluate a Session Expression.
    /// The returned object can be passed to GetSessionExpressionValue and other similar methods.
    ///
    /// It is recommended to use CreateTypedSessionExpressionOrNull to create a typed delegate instead.
    /// </summary>
    public static bool TryCreateSessionExpression(string str, [NotNullWhen(true)] out object? expression) {
        return TryCreateSessionExpression(str, ExpressionContext.Default, out expression);
    }
    
    /// <summary>
    /// Creates an object which can evaluate a Session Expression, using the given Session Expression Context.
    /// The context object should be generated by <see cref="CreateSessionExpressionContextV2"/>.
    /// The returned object can be passed to GetSessionExpressionValue and other similar methods.
    /// 
    /// It is recommended to use CreateTypedSessionExpressionOrNull to create a typed delegate instead.
    /// </summary>
    public static bool TryCreateSessionExpression(string str, object? context, [NotNullWhen(true)] out object? expression) {
        if (ConditionHelper.TryCreate(str, AssertIsOrNull<IExpressionContext>(context) ?? ExpressionContext.Default, out var expr)) {
            expression = CompiledCondition<object>.GetFor(expr);
            return true;
        }

        expression = null;
        return false;
    }

