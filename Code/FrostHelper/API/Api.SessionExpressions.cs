    private static CompiledCondition<object> AssertExpression(object expression) {
        if (expression is not CompiledCondition<object> expr) {
            throw new ArgumentException($"Object '{expression}' is not of type {nameof(ConditionHelper.Condition)}!");
        }

        return expr;
    }
    
    // NON-API!
    private static ExpressionContext AssertContext(object ctx) {
        if (ctx is not ExpressionContext expr) {
            throw new ArgumentException($"Object '{ctx}' is not of type {nameof(ExpressionContext)}!");
        }

        return expr;
    }
    
    // NON-API!
    private static T AssertIs<T>(object ctx) {
        if (ctx is not T expr) {
            throw new ArgumentException($"Object '{ctx}' is not of type {typeof(T)}!");
        }

        return expr;
    }
    
    // NON-API!
    private static T? AssertIsOrNull<T>(object? ctx) where T : class {
        if (ctx is not T expr) {
            if (ctx is null)
                return null;

            throw new ArgumentException($"Object '{ctx}' is not of type {typeof(T)}!");
        }

        return expr;
    }
    
        internal class InvalidUserdataTypeException(Type expected, Type? actual) : Exception {
        public override string Message => $"Userdata type was invalid, expected '{expected}', received '{actual?.Name ?? "null"}'";
    }
    
    private sealed class ModApiSimpleCommandV2(Delegate func, int argCount, Type? requiredUserdataType) : ConditionHelper.Condition {
        private DynamicReferenceCell _cell;
        private object?[]? _args;

        private static readonly MethodInfo ThrowInvalidUserdataExceptionIfNeededMethodInfo
            = typeof(ModApiSimpleCommandV2).GetMethod(nameof(ThrowInvalidUserdataExceptionIfNeeded), BindingFlags.Static | BindingFlags.NonPublic)!;
        
        public override object Get(Session session, object? userdata) {
            _args ??= new object[argCount];
            var args = _args;
            switch (args.Length) {
                case >= 2:
                    if (userdata is null) {
                        if (requiredUserdataType is not null)
                            throw new InvalidUserdataTypeException(requiredUserdataType!, null);
                        args[1] = null;
                        goto case 1; // fallthrough
                    }
                    
                    if (!userdata.GetType().IsAssignableTo(requiredUserdataType)) {
                        throw new InvalidUserdataTypeException(requiredUserdataType!, userdata.GetType());
                    }
                    
                    args[1] = userdata;
                    goto case 1; // fallthrough
                case 1:
                    args[0] = session;
                    break;
            }
            
            var ret = func.DynamicInvoke(_args);
            if (ret is bool b)
                return BoolToBoxedInt(b);
            return ret!;
        }

        internal override void Emit(ConditionCompilationCtx ctx, Type targetType) {
            var method = func.Method;
            if (func.Target is not null) {
                if (_cell != default) {
                    ctx.Il.EmitLoadReference(_cell);
                } else {
                    ctx.Il.EmitNewReference(func.Target, out _cell);
                }
            }

            if (argCount > 0)
                ctx.EmitLoadSession();
            if (argCount > 1) {
                ctx.EmitLoadUserdata();
                if (requiredUserdataType is not null) {
                    ctx.Il.Emit(OpCodes.Call, ThrowInvalidUserdataExceptionIfNeededMethodInfo.MakeGenericMethod(requiredUserdataType));
                }
            }
            ctx.Il.Emit(OpCodes.Call, method);
            ctx.EmitConvertTo(method.ReturnType, targetType);
        }

        private static TUserdata ThrowInvalidUserdataExceptionIfNeeded<TUserdata>(object? userdata) {
            if (userdata is not TUserdata cast)
                throw new InvalidUserdataTypeException(typeof(TUserdata), userdata?.GetType());

            return cast;
        }

        internal override bool UsesCurrentConditionLocalInEmit => false;

        protected internal override Type ReturnType => Descriptor!.ReturnType.CSharpType;

        protected override IEnumerable<object> GetArgsForDebugPrint() => [func];
    }
    
    private sealed class ModFunctionConditionV2(IReadOnlyList<ConditionHelper.Condition> args, Delegate func, ParameterInfo[] parameterInfos, Type? requiredUserdataType) 
        : FunctionCommands.FunctionCondition(args) {
        
        private DynamicReferenceCell _cell;
        
        private readonly object?[] _array = new object[args.Count + 2];
        private ConditionHelper.Condition GetArg(int index) => args[index];

        private static readonly MethodInfo MethodGetArg =
            typeof(ModFunctionConditionV2).GetMethod(nameof(GetArg), BindingFlags.Instance | BindingFlags.NonPublic)!;
        
        private static readonly MethodInfo ThrowInvalidUserdataExceptionIfNeededMethodInfo
            = typeof(ModApiSimpleCommandV2).GetMethod(nameof(ThrowInvalidUserdataExceptionIfNeeded), BindingFlags.Static | BindingFlags.NonPublic)!;
        
        public override object Get(Session session, object? userdata) {
            var arr = _array;
            arr[0] = session;
            if (userdata is null) {
                if (requiredUserdataType is not null)
                    throw new InvalidUserdataTypeException(requiredUserdataType!, null);
            } else if (!userdata.GetType().IsAssignableTo(requiredUserdataType)) {
                throw new InvalidUserdataTypeException(requiredUserdataType!, userdata.GetType());
            }
            arr[1] = userdata;

            for (int i = 0; i < args.Count; i++) {
                arr[i + 2] = Coerce(args[i].Get(session, userdata), parameterInfos[i + 2].ParameterType);
            }
            
            return func.DynamicInvoke(_array)!;
        }

        protected internal override Type ReturnType { get; } = func.Method.ReturnType;

        internal override void Emit(ConditionCompilationCtx ctx, Type targetType) {
            var il = ctx.Il;
            var method = func.Method;
            LocalBuilder? tempOrigCond = null;
            
            if (func.Target is not null) {
                if (_cell != default) {
                    ctx.Il.EmitLoadReference(_cell);
                } else {
                    ctx.Il.EmitNewReference(func.Target, out _cell);
                }
            }
            if (parameterInfos.Length > 0)
                ctx.EmitLoadSession();
            if (parameterInfos.Length > 1) {
                ctx.EmitLoadUserdata();
                if (requiredUserdataType is not null) {
                    ctx.Il.Emit(OpCodes.Call, ThrowInvalidUserdataExceptionIfNeededMethodInfo.MakeGenericMethod(requiredUserdataType));
                }
            }
            
            var i = 0;
            foreach (var arg in args) {
                var parameterInfo = parameterInfos[i + 2];
                il.EmitSwapOutCurrentCondition(ref tempOrigCond, ctx, arg, () => {
                    il.Emit(OpCodes.Ldloc, tempOrigCond!);
                    il.Emit(OpCodes.Ldc_I4, i);
                    il.Emit(OpCodes.Call, MethodGetArg);
                });
                arg.Emit(ctx, parameterInfo.ParameterType);
                i++;
            }
            
            il.EmitRevertCurrentCondition(tempOrigCond, ctx);
            
            ctx.Il.Emit(OpCodes.Call, method);
            ctx.EmitConvertTo(method.ReturnType, targetType);
        }

        internal override bool UsesCurrentConditionLocalInEmit => args.Any(a => a.UsesCurrentConditionLocalInEmit);
        
        private static TUserdata ThrowInvalidUserdataExceptionIfNeeded<TUserdata>(object? userdata) {
            if (userdata is not TUserdata cast)
                throw new InvalidUserdataTypeException(typeof(TUserdata), userdata?.GetType());

            return cast;
        }
    }
