    /// <summary>
    /// Registers a simple Session Expression command, which will be accessible in Session Expressions via
    /// - $cmdName if a context is provided,
    /// - $modName.cmdName if the command is global (no context is provided).
    /// Added in Frost Helper 1.81.0
    /// </summary>
    /// <param name="modName">Name of the mod which registers this command. Will be used to prefix the command name.</param>
    /// <param name="cmdName">Name of the command</param>
    /// <param name="context">The Expression Context, created via CreateSessionExpressionContextV2, to register this command to. Leave null to register the command globally.</param>
    /// <param name="command">
    /// Function called each time the command needs to be evaluated. Must have a return type.
    /// May accept up to 2 arguments, where the first one is a Session, and the second is userdata.
    /// Userdata is object? by default, it can be typed as a different type if the command is registered non-globally.
    /// If userdata is not typed as object?, and the correct userdata type is not passed when evaluating the command, an exception will be thrown.
    ///
    /// For optimal performance, make sure the delegate is created from a static method, like:
    /// <code>
    /// static void Register() {
    ///     RegisterSimpleSessionExpressionCommandV2("yourMod", "three", null, [], Three);
    /// }
    /// 
    /// static int Three() {
    ///    return 3;
    /// }
    /// </code>
    /// </param>
    /// <param name="description">Description of this command, visible in Mapping Utils. (ApiRenderPart is defined in Api.RenderPart.cs)</param>
    public static void RegisterSimpleSessionExpressionCommandV2(string modName, string cmdName, object? context, 
        IReadOnlyList<ApiRenderPart> description, Delegate command) {
        var key = context is null ? $"{modName}.{cmdName}" : cmdName;
        var method = command.Method;

        if (method.ReturnType == typeof(void)) {
            throw new Exception("Simple command delegate must return a value.");
        }

        var desc = new CommandDescriptor {
            Name = key,
            DeclaringMod = modName,
            DeclaringType = null,
            Description = RenderPart.FromApi(description),
            Arguments = [],
            ReturnType = TypeDescriptor.For(method.ReturnType),
        };

        var delegateParameters = command.Method.GetParameters();
        Type? requiredUserdataType = null;
        if (delegateParameters.Length > 2) {
            throw new Exception($"Simple command delegates can only accept up to 2 parameters! '{key}' has '{delegateParameters.Length}' parameters");
        }
        
        if (delegateParameters.Length > 1 && delegateParameters[1].ParameterType != typeof(object)) {
            requiredUserdataType = delegateParameters[1].ParameterType;

            if (!requiredUserdataType.IsClass)
                throw new Exception("Userdata can only be a class.");

            if (context is null) {
                throw new Exception($"Command {key} requires a specific userdata type ({requiredUserdataType}), which is not supported when registering a global command. Provide a custom Expression Context to register the command to, or accept object? as the userdata and handle type mismatches inside your delegate.");
            }
        }

        if (delegateParameters.Length > 0 && delegateParameters[0].ParameterType != typeof(Session)) {
            throw new Exception($"Simple command delegate's first parameter must be of type Session. '{key}' has '{delegateParameters[0].ParameterType}'");
        }
        
        var commandCondition = new ModApiSimpleCommandV2(command, delegateParameters.Length, requiredUserdataType) { Descriptor = desc };
        
        if (AssertIsOrNull<IExpressionContext>(context) is { } ctx) {
            ctx.RegisterSimpleCommand(key, commandCondition);
            return;
        }

        SimpleCommands.Registry[key] = new SimpleCommand(desc, commandCondition);
    }

    /// <summary>
    /// Registers a simple Session Expression function, which will be accessible in Session Expressions via
    /// - $cmdName(...) if a context is provided,
    /// - $modName.cmdName(...) if the command is global (no context is provided).
    /// </summary>
    /// Added in Frost Helper 1.81.0
    /// <param name="modName">Name of the mod which registers this command. Will be used to prefix the command name.</param>
    /// <param name="cmdName">Name of the command</param>
    /// <param name="context">The Expression Context, created via CreateSessionExpressionContextV2, to register this command to. Leave null to register the command globally.</param>
    /// <param name="func">
    /// Function called each time the function needs to be evaluated. Must have a return type.
    /// MUST accept at least 2 arguments, where the first one is a Session, and the second is userdata.
    /// Userdata is object? by default, it can be typed as a different type if the command is registered non-globally.
    /// If userdata is not typed as object?, and the correct userdata type is not passed when evaluating the function, an exception will be thrown.
    ///
    /// The delegate may accept more than 2 arguments, in which case all further arguments will be obtained from the Session Expression.
    /// These arguments may accept any C# type, arguments will be coerced automatically using usual Session Expression rules.
    /// 
    /// For optimal performance, make sure the delegate is created from a static method, like:
    /// <code>
    /// static void Register() {
    ///     RegisterFunctionSessionExpressionCommandV2("yourMod", "sum", null, [], Sum);
    /// }
    /// 
    /// static int Sum(Session session, object? userdata, int a, int b) {
    ///    return a + b;
    /// }
    /// </code>
    /// </param>
    /// <param name="description">Description of this function, visible in Mapping Utils. (ApiRenderPart is defined in Api.RenderPart.cs)</param>
    public static void RegisterFunctionSessionExpressionCommandV2(string modName, string cmdName, object? context, IReadOnlyList<ApiRenderPart> description, Delegate func) {
        var key = context is null ? $"{modName}.{cmdName}" : cmdName;
        var method = func.Method;
        var delegateParameters = method.GetParameters();
        if (delegateParameters.Length < 2) {
            throw new Exception("Function command delegates must have at least two parameters: Session, userdata");
        }

        if (delegateParameters[0].ParameterType != typeof(Session)) {
            throw new Exception("Function command delegates' first argument must be Session");
        }
        
        Type? requiredUserdataType = null;
        if (delegateParameters[1].ParameterType != typeof(object)) {
            requiredUserdataType = delegateParameters[1].ParameterType;

            if (!requiredUserdataType.IsClass)
                throw new Exception("Userdata can only be a class.");

            if (context is null) {
                throw new Exception($"Function {key} requires a specific userdata type ({requiredUserdataType}), which is not supported when registering a global command. Provide a custom Expression Context to register the command to, or accept object? as the userdata and handle type mismatches inside your delegate.");
            }
        }
        
        var desc = new CommandDescriptor {
            Name = key,
            DeclaringMod = modName,
            ReturnType = TypeDescriptor.For(method.ReturnType),
            Arguments = delegateParameters.Skip(2).Select(p => new ArgumentDescriptor(p.Name ?? "", TypeDescriptor.For(p.ParameterType))).ToList(),
            DeclaringType = null,
            Description = RenderPart.FromApi(description),
        };
        var cmd = new FunctionCommand(((args, out result, out message) => {
            if (args.Count != desc.Arguments.Count) {
                message = $"Function {desc.Name} requires {desc.Arguments.Count} arguments, received {args.Count}";
                result = null;
                return false;
            }
            
            result = new ModFunctionConditionV2(args, func, delegateParameters, requiredUserdataType);
            result.Descriptor = desc;
            message = null;
            return true;
        }), desc);
        
        if (AssertIsOrNull<IExpressionContext>(context) is { } ctx) {
            ctx.RegisterFunctionCommand(key, cmd);
            return;
        }

        FunctionCommands.Registry[key] = cmd;
    }

